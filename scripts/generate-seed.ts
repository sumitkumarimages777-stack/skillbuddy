/**
 * Writes supabase/seed.sql from src/lib/demo-data.ts.
 * Run: npm run seed:sql
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { demoCourses, demoFaqs, demoMentors, demoReviews } from "../src/lib/demo-data.ts";

type Value = string | number | boolean | null | string[];

function lit(v: Value): string {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  if (Array.isArray(v)) return v.length ? `array[${v.map(lit).join(", ")}]::text[]` : "'{}'::text[]";
  return `'${v.replace(/'/g, "''")}'`;
}

function insert(table: string, rows: Record<string, Value>[]): string {
  if (!rows.length) return "";
  const cols = Object.keys(rows[0]);
  const values = rows.map((r) => `  (${cols.map((c) => lit(r[c])).join(", ")})`).join(",\n");
  return `insert into public.${table} (${cols.join(", ")}) values\n${values}\non conflict do nothing;\n\n`;
}

let sql = "-- Generated by scripts/generate-seed.ts from src/lib/demo-data.ts. Do not edit by hand.\n\n";

sql += insert(
  "mentors",
  demoMentors.map((m) => ({
    id: m.id, name: m.name, role: m.role, company: m.company, track: m.track, bio: m.bio,
    photo_url: m.photo_url, linkedin_url: m.linkedin_url, published: m.published, sort_order: m.sort_order,
  })),
);

sql += insert(
  "courses",
  demoCourses.map((c) => ({
    id: c.id, slug: c.slug, title: c.title, short_title: c.short_title, short_code: c.short_code,
    category: c.category, blurb: c.blurb, description: c.description, duration_weeks: c.duration_weeks,
    format: c.format, mode: c.mode, effort: c.effort, batch_size: c.batch_size, start_date: c.start_date,
    applications_close: c.applications_close, price: c.price, emi_from: c.emi_from,
    dubuddy_discount: c.dubuddy_discount, seats_left: c.seats_left, outcomes: c.outcomes,
    syllabus_url: c.syllabus_url, lead_mentor_id: c.lead_mentor_id, guest_mentors_note: c.guest_mentors_note,
    featured: c.featured, published: c.published, sort_order: c.sort_order,
  })),
);

sql += insert(
  "course_modules",
  demoCourses.flatMap((c) =>
    c.modules.map((m, i) => ({ course_id: c.id, position: i, weeks_label: m.weeks_label, title: m.title, topics: m.topics, assignment: m.assignment })),
  ),
);
sql += insert(
  "course_projects",
  demoCourses.flatMap((c) =>
    c.projects.map((p, i) => ({ course_id: c.id, position: i, title: p.title, description: p.description, accent: p.accent, image_url: p.image_url })),
  ),
);
sql += insert(
  "course_batches",
  demoCourses.flatMap((c) => c.batches.map((b, i) => ({ course_id: c.id, position: i, name: b.name, schedule: b.schedule }))),
);
sql += insert(
  "course_week_plan",
  demoCourses.flatMap((c) =>
    c.week_plan.map((w, i) => ({ course_id: c.id, position: i, day_label: w.day_label, activity: w.activity, detail: w.detail })),
  ),
);

sql += insert(
  "reviews",
  demoReviews.map((r) => ({
    id: r.id, learner_name: r.learner_name, college: r.college, outcome_role: r.outcome_role,
    outcome_company: r.outcome_company, course_id: r.course_id, quote: r.quote, photo_url: r.photo_url,
    published: r.published, sort_order: r.sort_order,
  })),
);
sql += insert(
  "faqs",
  demoFaqs.map((f) => ({ id: f.id, question: f.question, answer: f.answer, published: f.published, sort_order: f.sort_order })),
);

const out = fileURLToPath(new URL("../supabase/seed.sql", import.meta.url));
writeFileSync(out, sql);
console.log(`Wrote ${out}`);
